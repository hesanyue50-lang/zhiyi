    /** 按关键词长度降序，长词优先，避免「典」把「典中典」吃掉 */
    private val SORTED = BANK.sortedByDescending { it.first.length }

    /**
     * 找出这段话里用到的梗。
     * 最多返回 6 条——多了会把 prompt 撑满，反而稀释真正重要的信息。
     */
    fun hits(text: String, max: Int = 6): List<Pair<String, String>> {
        if (text.isBlank()) return emptyList()
        val t = text.lowercase()
        val out = ArrayList<Pair<String, String>>()
        val used = ArrayList<String>()
        for ((kw, meaning) in SORTED) {
            if (out.size >= max) break
            val k = kw.lowercase()
            if (!t.contains(k)) continue
            // 已经命中一个包含它的长词就跳过（「破大防」命中后不必再报「破防」）
            if (used.any { it.contains(kw) }) continue
            out.add(kw to meaning)
            used.add(kw)
        }
        return out
    }

    /** 拼成一段可以直接塞进 prompt 的说明 */
    fun hint(text: String): String {
        val h = hits(text)
        if (h.isEmpty()) return ""
        val sb = StringBuilder("# 对方用到的一些流行说法（你听得懂，但不必刻意解释）\n")
        h.forEach { (kw, meaning) -> sb.append("- ").append(kw).append("：").append(meaning).append("\n") }
        sb.append("（知道意思就行，正常接话，别像在给人科普。）\n")
        return sb.toString()
    }
